# ---------------------------------------------------------------------------------------------
# JSON-LD
# ---------------------------------------------------------------------------------------------

def url_of(page: dict) -> str:
    return SITE + page["path"]


def breadcrumb(page: dict) -> dict:
    items = []
    for position, (name, path) in enumerate(page["crumbs"], start=1):
        item = {"@type": "ListItem", "position": position, "name": name}
        if path is not None:
            item["item"] = SITE + path
        items.append(item)
    return {
        "@type": "BreadcrumbList",
        "@id": f"{url_of(page)}#breadcrumb",
        "itemListElement": items,
    }


def graph(page: dict) -> dict:
    url = url_of(page)
    webpage = {
        "@type": "WebPage",
        "@id": f"{url}#webpage",
        "url": url,
        "name": page["title"],
        "description": page["description"],
        "inLanguage": "en",
        "isPartOf": {"@id": WEBSITE_ID},
        "about": {"@id": PROJECTS[page["about"][0]]["@id"]},
    }
    nodes: list[dict] = [ORGANIZATION]
    if page["path"] == "/":
        nodes.append(
            {
                "@type": "WebSite",
                "@id": WEBSITE_ID,
                "url": f"{SITE}/",
                "name": SITE_NAME,
                "alternateName": ["mikrotik-mcp", "MikroTik MCP server"],
                "description": page["description"],
                "inLanguage": "en",
                "publisher": {"@id": ORG_ID},
            }
        )
    else:
        # The WebSite node lives on the home page; docs pages only point at it.
        webpage["isPartOf"] = {"@id": WEBSITE_ID, "@type": "WebSite", "url": f"{SITE}/", "name": SITE_NAME}
    nodes.append(webpage)
    if page["crumbs"]:
        webpage["breadcrumb"] = {"@id": f"{url}#breadcrumb"}
        nodes.append(breadcrumb(page))
    for key in page["about"]:
        project = dict(PROJECTS[key])
        project["author"] = {"@id": ORG_ID}
        project["publisher"] = {"@id": ORG_ID}
        nodes.append(project)
    return {"@context": "https://schema.org", "@graph": nodes}


def json_ld(page: dict) -> str:
    text = json.dumps(graph(page), ensure_ascii=False, indent=2)
    # Nothing in the data can close the script element, but keep it that way if the table grows.
    return text.replace("</", "<\\/")


# ---------------------------------------------------------------------------------------------
# Head block
# ---------------------------------------------------------------------------------------------

def attr(value: str) -> str:
    return html.escape(value, quote=True)


def head_block(page: dict) -> str:
    url = url_of(page)
    title, desc = attr(page["title"]), attr(page["description"])
    lines = [
        MARK_START,
        f'<link rel="canonical" href="{attr(url)}" />',
        '<meta name="robots" content="index, follow, max-image-preview:large" />',
        '<meta property="og:type" content="website" />',
        f'<meta property="og:site_name" content="{attr(SITE_NAME)}" />',
        '<meta property="og:locale" content="en_US" />',
        f'<meta property="og:title" content="{title}" />',
        f'<meta property="og:description" content="{desc}" />',
        f'<meta property="og:url" content="{attr(url)}" />',
        f'<meta property="og:image" content="{attr(OG_IMAGE)}" />',
        '<meta property="og:image:type" content="image/png" />',
        '<meta property="og:image:width" content="1200" />',
        '<meta property="og:image:height" content="630" />',
        f'<meta property="og:image:alt" content="{attr(OG_IMAGE_ALT)}" />',
        '<meta name="twitter:card" content="summary_large_image" />',
        f'<meta name="twitter:title" content="{title}" />',
        f'<meta name="twitter:description" content="{desc}" />',
        f'<meta name="twitter:image" content="{attr(OG_IMAGE)}" />',
        f'<meta name="twitter:image:alt" content="{attr(OG_IMAGE_ALT)}" />',
        '<script type="application/ld+json">',
        json_ld(page),
        "</script>",
        MARK_END,
    ]
    return "\n".join(lines)


TITLE_RE = re.compile(r"<title>.*?</title>", re.S)
DESC_RE = re.compile(r'<meta name="description" content="[^"]*"\s*/?>', re.S)
BLOCK_RE = re.compile(r"[ \t]*" + re.escape(MARK_START) + r".*?" + re.escape(MARK_END) + r"\r?\n?", re.S)


def render(page: dict, text: str) -> str:
    """Return `text` with this page's SEO tags applied. `text` uses LF line endings."""
    text = BLOCK_RE.sub("", text)
    title_tag = f"<title>{attr(page['title'])}</title>"
    desc_tag = f'<meta name="description" content="{attr(page["description"])}" />'
    if not TITLE_RE.search(text) or not DESC_RE.search(text):
        raise SystemExit(f"{page['file']}: needs a <title> and a meta description to anchor on")
    text = TITLE_RE.sub(lambda _m: title_tag, text, count=1)
    text = DESC_RE.sub(lambda _m: desc_tag + "\n" + head_block(page), text, count=1)
    return text


def read_page(path: Path) -> tuple[str, str]:
    raw = path.read_bytes().decode("utf-8")
    eol = "\r\n" if "\r\n" in raw else "\n"
    return raw.replace("\r\n", "\n"), eol


def write_page(path: Path, text: str, eol: str) -> None:
    path.write_bytes(text.replace("\n", eol).encode("utf-8"))


# ---------------------------------------------------------------------------------------------
# Sitemap
# ---------------------------------------------------------------------------------------------

def git(*args: str) -> str:
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True, check=True).stdout.strip()


def lastmod(page: dict) -> str:
    """The date the page last changed: the last commit, or today if it has uncommitted edits."""
    rel = f"website-src/{page['file']}"
    if git("status", "--porcelain", "--", rel):
        return datetime.date.today().isoformat()
    return git("log", "-1", "--format=%cs", "--", rel) or datetime.date.today().isoformat()


def sitemap(dates: dict[str, str]) -> str:
    out = ['<?xml version="1.0" encoding="UTF-8"?>', '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">']
    for page in PAGES:
        out.append(f"  <url><loc>{url_of(page)}</loc><lastmod>{dates[page['file']]}</lastmod></url>")
    out.append("</urlset>")
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------------------------------------
# Commands
# ---------------------------------------------------------------------------------------------

def build() -> None:
    changed = []
    for page in PAGES:
        path = SRC / page["file"]
        text, eol = read_page(path)
        new = render(page, text)
        if new != text:
            write_page(path, new, eol)
            changed.append(page["file"])
    dates = {p["file"]: lastmod(p) for p in PAGES}
    (SRC / "sitemap.xml").write_bytes(sitemap(dates).encode("utf-8"))
    print(f"pages updated: {len(changed)}/{len(PAGES)}; sitemap.xml lists {len(PAGES)} URLs")


def check() -> int:
    problems: list[str] = []
    seen_titles: set[str] = set()
    seen_desc: set[str] = set()
    for page in PAGES:
        name = page["file"]
        path = SRC / name
        if not path.exists():
            problems.append(f"{name}: file missing")
            continue
        text, _ = read_page(path)
        if render(page, text) != text:
            problems.append(f"{name}: head is out of date, run `python tools/seo.py build`")
        if len(page["title"]) > TITLE_MAX:
            problems.append(f"{name}: title is {len(page['title'])} characters (max {TITLE_MAX})")
        if not DESC_MIN <= len(page["description"]) <= DESC_MAX:
            problems.append(f"{name}: description is {len(page['description'])} characters ({DESC_MIN}-{DESC_MAX})")
        if page["title"] in seen_titles:
            problems.append(f"{name}: duplicate title")
        if page["description"] in seen_desc:
            problems.append(f"{name}: duplicate description")
        seen_titles.add(page["title"])
        seen_desc.add(page["description"])
        if len(re.findall(r"<h1[\s>]", text)) != 1:
            problems.append(f"{name}: needs exactly one <h1>")
        if re.search(r'href="(?:\.\./|\./)?index\.html', text):
            problems.append(f"{name}: links to index.html; link to the clean URL (/ or /docs/) instead")
        for block in re.findall(r'<script type="application/ld\+json">(.*?)</script>', text, re.S):
            try:
                json.loads(block)
            except ValueError as exc:
                problems.append(f"{name}: JSON-LD does not parse ({exc})")
    on_disk = {p.relative_to(SRC).as_posix() for p in SRC.rglob("*.html")} - {"404.html"}
    listed = {p["file"] for p in PAGES}
    for missing in sorted(on_disk - listed):
        problems.append(f"{missing}: page is not in tools/seo.py PAGES (and so not in the sitemap)")
    try:
        tree = ElementTree.parse(SRC / "sitemap.xml")
        ns = {"s": "http://www.sitemaps.org/schemas/sitemap/0.9"}
        locs = [e.text for e in tree.getroot().findall("s:url/s:loc", ns)]
        if locs != [url_of(p) for p in PAGES]:
            problems.append("sitemap.xml: URLs differ from PAGES, run `python tools/seo.py build`")
    except (OSError, ElementTree.ParseError) as exc:
        problems.append(f"sitemap.xml: {exc}")
    robots = (SRC / "robots.txt")
    if not robots.exists() or f"Sitemap: {SITE}/sitemap.xml" not in robots.read_text(encoding="utf-8"):
        problems.append("robots.txt: missing, or has no Sitemap line")
    for problem in problems:
        print("FAIL", problem)
    print("ok" if not problems else f"{len(problems)} problem(s)")
    return 1 if problems else 0


def main(argv: list[str]) -> int:
    if len(argv) != 2 or argv[1] not in {"build", "check"}:
        print(__doc__)
        return 2
    if argv[1] == "build":
        build()
        return 0
    return check()


if __name__ == "__main__":
    sys.exit(main(sys.argv))
